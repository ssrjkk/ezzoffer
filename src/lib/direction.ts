import { extractSkills } from "./skills";

/**
 * Направление и режим работы.
 *
 * Пользователь приходит не с запросом «покажи всё», а с запросом вида «хочу
 * подработку на вечер, фронтенд, джуном» или «фриланс, дизайн». Пока в
 * продукте нет ни направления, ни режима работы, такой запрос превращается в
 * «список из тысячи вакансий, ищи сам» — а это ровно та работа, которую человек
 * и не хотел делать.
 *
 * Классификация строится на трёх сигналах, взятых в указанном порядке: раздел
 * площадки (он задаёт направление точнее всего), затем заголовок, затем текст
 * описания. Сначала заголовок брать нельзя: «Разработчик в команду по
 * автоматизации с Python и React» не про Python, а про два слага — и выбор по
 * первому совпадению давал бы половину таких вакансий не в тот раздел.
 *
 * Приоритет направлений не alphabetical: бэкенд первее фронтенда, потому что
 * «React-разработчик» в заголовке фронтенд, а «Python-разработчик» с React в
 * описании — всё равно бэкенд. Порядок ниже это кодирует.
 */

export type Direction =
  | "frontend"
  | "backend"
  | "fullstack"
  | "mobile"
  | "data"
  | "devops"
  | "design"
  | "qa"
  | "pm"
  | "sales"
  | "other";

export const DIRECTION_LABELS: Record<Direction, string> = {
  frontend: "Фронтенд",
  backend: "Бэкенд",
  fullstack: "Фулстек",
  mobile: "Мобильная разработка",
  data: "Данные и аналитика",
  devops: "DevOps и инфраструктура",
  design: "Дизайн",
  qa: "Тестирование",
  pm: "Управление и аналитика",
  sales: "Продажи и маркетинг",
  other: "Другое",
};

/**
 * Режим работы.
 *
 * «Подработка» и «фриланс» — разные вещи, и человек обычно знает, какая ему
 * нужна. Подработка предполагает договор с работодателем и стабильный поток;
 * фриланс — заказы по одной. Смешивать их в один список значит отвечать не на
 * тот вопрос, который задали.
 */
export type WorkMode = "подработка" | "фриланс" | "основная";

export const WORK_MODE_LABELS: Record<WorkMode, string> = {
  подработка: "Подработка",
  фриланс: "Фриланс и заказы",
  основная: "Основная работа",
};

/** Разделы площадок. Проверяются по вхождению, порядок — от точного к общему. */
const CATEGORY_DIRECTION: [RegExp, Direction][] = [
  [/1с/i, "backend"],
  [/битрикс|bitrix|crm|erp/i, "backend"],
  /*
   * Язык в разделе площадки.
   *
   * У fl.ru раздел устроен как «Программирование / Python», и без этого правила
   * он не попадал ни в одно направление: общее правило на «программирование»
   * пришлось убрать — оно перебивало заголовок и отправляло «Frontend-разработчик»
   * в бэкенд. Теперь общий раздел понижен, а конкретный подраздел разбирается
   * здесь.
   */
  [/(\bpython|php|golang|\bgo\b|java|c#|\.net|node\.?js|ruby|perl|scala|kotlin)/i, "backend"],
  [/разработка (?:мобильных |приложений |игр |игровых )?(?:на )?(?:ios|android)/i, "mobile"],
  [/ios|android|мобильн|flutter|react ?native/i, "mobile"],
  [/сайт|лендинг|веб-разработ|frontend|фронтенд|вёрстк/i, "frontend"],
  [/wordpress|битрикс24/i, "frontend"],
  [/3d|график|дизайн|дизайнер|иллюстра|баннер|логотип/i, "design"],
  [/seo|продвижен|маркетинг|реклам|таргет|перфоманс/i, "sales"],
  [/продажи|лид|менеджер/i, "sales"],
  [/тестирован|qa|автотест/i, "qa"],
  [/аналитик|анализ|product|продукт|project ?manager|\bpm\b/i, "pm"],
  [/data|данн|ml\b|machine learning|машинн|ai\b|искусственн/i, "data"],
  /*
   * Автоматизация бизнеса через таблицы и Excel.
   *
   * На fl.ru это «Автоматизация бизнеса / Таблицы / Excel» — постоянная рубрика
   * и самый частый вход в фриланс для человека без опыта, что и требуется от
   * раздела для любого грейда. Формулировка узкая намеренно: «Автоматизация»
   * в «Инжиниринг / Слаботочные сети/Автоматизация» — это электрика, а не
   * таблицы, и ловить её общим словом нельзя.
   */
  [/таблиц|excel|автоматизаци[яи] бизнеса/i, "data"],
  [/devops|системн|администр|инфраструктур|linux|сервер|ci\/cd|docker|kubernetes/i, "devops"],
];

/** Заголовок: тот же принцип, но короче — только явные признаки. */
const TITLE_DIRECTION: [RegExp, Direction][] = [
  [
    /(^|\W)(ios|android|flutter|react ?native)(\W|$)|мобильн|сотовых телефон|под android|под ios/i,
    "mobile",
  ],
  [/(^|\W)(devops|sre|системный администратор)(\W|$)/i, "devops"],
  [/(^|\W)(qa|тестировщик)(\W|$)/i, "qa"],
  [/(^|\W)(аналитик|product manager)(\W|$)/i, "pm"],
  [/(^|\W)(дизайнер|ux|ui)(\W|$)/i, "design"],
  [/(fullstack|full-stack|фулстек)/i, "fullstack"],
  [/(frontend|фронтенд|вёрстальщик|верстальщик)/i, "frontend"],
  [/(backend|бэкенд|бэк-end)/i, "backend"],
  /*
   * Язык в заголовке — тоже направление, и довольно точное: «Python-разработчик»
   * с React в требованиях это бэкенд. Без этого правила заголовок не давал
   * ничего, и вакансия уходила в «fullstack» по навыкам из описания.
   */
  [/(?<![а-яёa-z0-9])(python|golang|go|java|php|1c|1с|node\.?js|системный администратор|сетевой)(?![а-яёa-z0-9])/i, "backend"],
  [/(?<![а-яёa-z0-9])(data|данн)/i, "data"],
];

/**
 * Навыки, по которым видно направление.
 *
 * Порядок значит: бэкенд до фронтенда. Вакансия «Python-разработчик», где в
 * требованиях React, — это бэкенд с фронтенд-частью, а не фронтенд с
 * серверной частью; человек, ищущий фронтенд, от такого отклика не получит
 * того, что хотел.
 */
const SKILL_DIRECTION: [string, Direction][] = [
  ["Kubernetes", "devops"],
  ["Docker", "devops"],
  ["PostgreSQL", "backend"],
  ["Kafka", "data"],
  ["Redis", "backend"],
  ["Python", "backend"],
  ["Go", "backend"],
  ["Java", "backend"],
  ["PHP", "backend"],
  ["React", "frontend"],
  ["Vue", "frontend"],
  ["Angular", "frontend"],
  ["TypeScript", "frontend"],
  ["JavaScript", "frontend"],
  ["Figma", "design"],
  ["CSS", "frontend"],
  ["ReactNative", "mobile"],
  ["Swift", "mobile"],
  ["Kotlin", "mobile"],
  ["SQL", "data"],
  ["Git", "devops"],
];

/**
 * Признаки подработки и проектной работы в тексте вакансии.
 *
 * Список составлен по формулировкам, которые площадки используют на самом деле,
 * а не по переводу с английского: «частичная занятость», «неполный день»,
 * «гибкий график» — так это и звучит в вакансиях.
 *
 * Важная оговорка: hh отдаёт отдельное поле занятости, но проверить его из
 * среды разработки нельзя — поиск требует токена приложения и отдаёт 403 на
 * любые параметры, включая рабочие. Поэтому режим определяется по тексту, а
 * структурное поле, если оно появится, должно проверяться первым.
 */
const SIDEGIG_WORDS = new RegExp(
  [
    "подработк",
    "частичн[а-яё]* занят",
    "частичная занятость",
    "неполный (?:день|рабочий день)",
    "проектн[а-яё]+ (?:работ|занят)",
    "работа по проекту",
    "фриланс",
    "part[- ]?time",
    "freelance",
    "совместительств",
    "гибкий график",
    "удалёнк[а-яё]* на (?:вечер|нескольк[а-яё]+ часов)",
    "не более \\d+ ?ч",
    "занятость.{0,12}\\d+ ?ч",
    // «проект» без слова «работа» — самое частое написание в заголовках:
    // «Проект под ключ», «Проект на 3 месяца».
    "заказчик ищет",
  ].join("|"),
  "iu",
);

/** Признаки основной работы, важнее отсутствия подработки. */
const FULLTIME_WORDS =
  /(полная занятость|full[- ]?time|работа в офисе полный день|5\/2|совместительство не требуется)/i;

/**
 * Определяет направление.
 *
 * `category` — раздел площадки, `title` — заголовок, `text` — описание с
 * требованиями. Ни одно из полей не обязательно: провайдер, у которого есть
 * только заголовок, работает.
 */
/**
 * Разделы, которые ничего не говорят о направлении.
 *
 * «Программирование» — их большинство: внутри него и фронтенд, и бэкенд, и 1С.
 * Проверяя раздел раньше заголовка, мы отдавали «Frontend-разработчик» в
 * бэкенд, потому что hh и fl.ru пишут в этот раздел всё подряд. Общий раздел —
 * слабый сигнал, и он не может перебивать явный заголовок, поэтому вынесен в
 * конец: применяется, только если заголовок и навыки не сказали ничего.
 */
const GENERIC_CATEGORIES = /^\s*(программирование|разработка|работа|it|и ?т)\s*$/i;

export function detectDirection(
  category: string | null | undefined,
  title: string,
  text = "",
): Direction {
  const cat = (category ?? "").trim();
  const head = title ?? "";
  const body = text ?? "";

  for (const [re, dir] of CATEGORY_DIRECTION) if (re.test(cat)) return dir;

  for (const [re, dir] of TITLE_DIRECTION) if (re.test(head)) return dir;

  const skills = extractSkills(`${head} ${body}`);
  const set = new Set(skills);

  /*
   * Фулстек проверяется до поштучного перебора навыков, а не после.
   *
   * При обратном порядке код не доходил до этой строки: перебор отдавал первую
   * подходящую роль, а Python и PostgreSQL стояли раньше React. Ветка «оба
   * фронта сразу» оказывалась недостижимой — фулстек не определялся никогда.
   *
   * При этом заголовок остаётся главным: «Python-разработчик» с React в
   * требованиях — это бэкенд с фронтенд-частью, и фулстеком называть его нельзя.
   * Фулстек означает, что в вакансии нет ведущей стороны.
   */
  const front = ["React", "Vue", "Angular", "CSS", "TypeScript"].some((s) => set.has(s));
  const back = ["Python", "Go", "Java", "PHP", "PostgreSQL", "Redis"].some((s) => set.has(s));
  if (front && back) return "fullstack";

  for (const [skill, dir] of SKILL_DIRECTION) if (set.has(skill)) return dir;

  if (!GENERIC_CATEGORIES.test(cat)) {
    for (const [re, dir] of CATEGORY_DIRECTION) if (re.test(cat)) return dir;
  }

  return "other";
}

/**
 * Определяет режим работы.
 *
 * `sourceIsFreelance` — заказ, а не вакансия: там подработки не бывает вовсе,
 * человек сам решает, сколько заказов взять. Это сильнее любого слова в
 * заголовке, поэтому проверяется первым.
 */
export function detectWorkMode(text: string, sourceIsFreelance = false): WorkMode {
  if (sourceIsFreelance) return "фриланс";
  const s = text ?? "";
  if (FULLTIME_WORDS.test(s)) return "основная";
  if (SIDEGIG_WORDS.test(s)) return "подработка";
  return "основная";
}

/**
 * Грейд для заказа, где площадка его не пишет.
 *
 * У заказов грейда нет в принципе: «сделать лендинг» не бывает джуном или
 * мидлом. Но вакансия может требовать студента, и тогда Senior — это
 * препятствие, а не завышение: человеку предлагают работу, которую ему не
 * предложили бы. Студентам и стажёрам отдаём Intern, остальное оставляем как
 * площадка написала.
 */
export function inferFreelanceLevel(title: string): Level {
  return /(студент|стаж[её]р|junior|джуниор|intern|начинающ)/i.test(title) ? "Intern" : "Middle";
}