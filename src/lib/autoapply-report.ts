import type { AutoApplyRun } from "./autoapply";

/**
 * Разбор прогона автоотклика.
 *
 * Панель автооткликов умела только включать и выключать его. Итог прогона жил в
 * логе планировщика, куда человек не заглядывает: отправилось ли что-то, куда
 * уходило, что мешало — видно было только при отладке.
 *
 * Тут важнее не сами числа, а причины. Человек после дня работы с сервисом
 * должен понять одно: почему откликов было столько, сколько было, и что
 * делать, если их мало.
 *
 * Модуль намеренно не импортирует БД: всё здесь — чистые функции от счётчиков
 * к тексту. Иначе проверка текста тянула бы за собой подключение к базе, и тест
 * правил бы её тем, что подставляет путь ДО импорта. Такой тест однажды
 * отработал на рабочей базе и оставил в ней битую запись.
 */

export type RunReason = {
  title: string;
  /** Что это значит для человека — не пересказ кода. */
  detail: string;
  tone: "good" | "warn" | "bad" | "muted";
};

export type LastRunReport = {
  at: number;
  applied: number;
  failed: number;
  skipped: number;
  stale: number;
  withLetter: number;
  pausedFor: string | null;
  reasons: RunReason[];
};

/**
 * Почему откликов было именно столько.
 *
 * Порядок ответа — по важности для человека, а не по порядку счётчиков.
 * Сначала то, что мешает прямо сейчас, потом то, что можно исправить, и лишь
 * потом то, что просто констатирует факт.
 */
export function explain(run: AutoApplyRun): RunReason[] {
  const out: RunReason[] = [];

  if (!run.ran) {
    return [
      {
        title: "Автоотклик не запускался",
        detail: run.reason ?? "Нет активных поисков у пользователей с активным тарифом.",
        tone: "warn",
      },
    ];
  }

  /*
   * Причины паузы.
   *
   * «backoff» после платформенного отказа — это защита аккаунта, и человек
   * должен знать про неё: иначе он смотрит на пустую панель и думает, что
   * сервис сломался. Формулировка объясняет и причину, и то, что это штатно.
   */
  if (run.pausedFor === "backoff") {
    out.push({
      title: "Отправка на паузе после отказа платформы",
      detail:
        "Платформа отклонила отклики, и темп снижен — это защита аккаунта от блокировки. " +
        "Пауза снимется сама. Если это повторяется каждый день, проверьте аккаунт hh и интернет-соединение.",
      tone: "warn",
    });
  }
  if (run.pausedFor === "daily") {
    out.push({
      title: "Дневной лимит откликов исчерпан",
      detail: "Отклики за сегодня закончились. Новые уйдут завтра.",
      tone: "muted",
    });
  }
  if (run.pausedFor === "hourly") {
    out.push({
      title: "Часовой лимит откликов исчерпан",
      detail: "Слишком много откликов за час. Следующие уйдут в новом часе — так выглядит живой человек, а не бот.",
      tone: "muted",
    });
  }
  if (run.pausedFor === "night") {
    out.push({
      title: "Ночное время",
      detail: "Отклики отправляются в рабочие часы. Ночью платформы чаще отказывают живому человеку.",
      tone: "muted",
    });
  }

  /*
   * Устаревшие вакансии — единственная причина пропуска, которую человек может
   * осознанно изменить. Если подходящих вакансий мало именно потому, что они
   * старые, то расширение поиска не поможет: нужны новые вакансии, а не более
   * широкие условия.
   */
  if (run.stale > 0) {
    out.push({
      title: `${run.stale} ${plural(run.stale, "подходящая вакансия старше", "подходящие вакансии старше", "подходящих вакансий старше")} двух дней`,
      detail:
        "На них отклик не отправлен намеренно: за это время вакансия обычно закрывается, " +
        "а отклик на закрытую тратит ваш дневной лимит и замедляет остальные отклики. " +
        "Если вакансий мало — расширьте поиск или добавьте новый.",
      tone: "warn",
    });
  }

  if (run.failed > 0) {
    out.push({
      // Склонение обязательно: «1 откликов не отправлено» — это то, что
      // человек видит в интерфейсе, и такая ошибка сразу читается как
      // невнимательность ко всему остальному тексту.
      title: `${run.failed} ${plural(run.failed, "отклик не отправлен", "отклика не отправлено", "откликов не отправлено")}`,
      detail: "Платформа их не приняла. Чаще всего это закрытая вакансия или превышен лимит на стороне hh.",
      tone: "bad",
    });
  }

  if (run.applied === 0 && run.failed === 0 && run.stale === 0) {
    out.push({
      title: "Подходящих вакансий не было",
      detail: "Каталог пуст по вашим условиям. Добавьте ключевые слова или снимите ограничения по городу и зарплате.",
      tone: "warn",
    });
  }

  if (run.applied > 0) {
    const withLetter = run.withLetter;
    out.push({
      title: `${run.applied} ${plural(run.applied, "отклик отправлен", "отклика отправлено", "откликов отправлено")}`,
      detail:
        withLetter === run.applied
          ? "К каждому приложено сопроводительное письмо."
          : `С письмом: ${withLetter} из ${run.applied}. Остальные ушли без него.`,
      tone: "good",
    });
  }

  return out;
}

/** Русские числительные: 1 отклик, 2 отклика, 5 откликов. */
export function plural(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return many;
  if (last > 1 && last < 5) return few;
  if (last === 1) return one;
  return many;
}